-- Phase 0 — Request identity + Better Auth tables.
--
-- The app connects as the database owner. Every user-scoped query runs inside a transaction that
-- switches to the `authenticated` role and sets `app.user_id` (src/lib/db/index.ts#withUser),
-- so RLS applies. Only Better Auth and maintenance scripts use the owner connection directly.

do $$
begin
  if not exists (select from pg_roles where rolname = 'authenticated') then
    create role authenticated nologin;
  end if;
end
$$;

grant authenticated to current_user;
grant usage on schema public to authenticated;

create schema app;
grant usage on schema app to authenticated;

-- Id of the user the current transaction acts for, or null.
create function app.current_user_id()
returns uuid
language sql
stable
set search_path = ''
as $$
  select nullif(current_setting('app.user_id', true), '')::uuid;
$$;

-- Better Auth tables (generated by scripts/print-auth-schema.mjs from src/lib/auth-options.ts).
-- Not tenant tables, never granted to `authenticated`.
create table users (
  id uuid default gen_random_uuid() not null primary key,
  name text not null,
  email text not null unique,
  email_verified boolean not null,
  image text,
  created_at timestamptz default current_timestamp not null,
  updated_at timestamptz default current_timestamp not null
);

create table sessions (
  id uuid default gen_random_uuid() not null primary key,
  expires_at timestamptz not null,
  token text not null unique,
  created_at timestamptz default current_timestamp not null,
  updated_at timestamptz not null,
  ip_address text,
  user_agent text,
  user_id uuid not null references users (id) on delete cascade
);

create table accounts (
  id uuid default gen_random_uuid() not null primary key,
  account_id text not null,
  provider_id text not null,
  user_id uuid not null references users (id) on delete cascade,
  access_token text,
  refresh_token text,
  id_token text,
  access_token_expires_at timestamptz,
  refresh_token_expires_at timestamptz,
  scope text,
  password text,
  created_at timestamptz default current_timestamp not null,
  updated_at timestamptz not null
);

create table verifications (
  id uuid default gen_random_uuid() not null primary key,
  identifier text not null,
  value text not null,
  expires_at timestamptz not null,
  created_at timestamptz default current_timestamp not null,
  updated_at timestamptz default current_timestamp not null
);

create index sessions_user_id_idx on sessions (user_id);
create index accounts_user_id_idx on accounts (user_id);
create index verifications_identifier_idx on verifications (identifier);

-- migrate:down
drop table verifications, accounts, sessions, users;
drop schema app cascade;
